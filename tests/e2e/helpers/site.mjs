import { readdir, readFile } from 'node:fs/promises';
import { join, posix } from 'node:path';
import { createServer } from 'node:http';
import assert from 'node:assert/strict';

export async function readSite(root) {
  const files=new Map();
  async function walk(directory,prefix='') {
    for(const entry of (await readdir(directory,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name,'en'))) {
      const relative=prefix+entry.name;
      if(entry.isDirectory()) await walk(join(directory,entry.name),relative+'/');
      else if(entry.isFile()) files.set(relative,await readFile(join(directory,entry.name)));
      else throw Error('output must contain only regular files/directories: '+relative);
    }
  }
  await walk(root);return new Map([...files].sort(([a],[b])=>a<b?-1:a>b?1:0));
}
export function compareSites(a,b) {
  assert.deepEqual([...a.keys()],[...b.keys()],'generated file list differs');
  for(const [name,bytes] of a) assert.ok(bytes.equals(b.get(name)),'generated bytes differ: '+name);
}
const mime={'.html':'text/html; charset=utf-8','.json':'application/json; charset=utf-8','.css':'text/css; charset=utf-8','.js':'text/javascript; charset=utf-8','.svg':'image/svg+xml','.png':'image/png','.woff2':'font/woff2','.txt':'text/plain; charset=utf-8'};
export async function serveSite(files) {
  const server=createServer((req,res)=>{
    res.setHeader('X-Content-Type-Options','nosniff');
    if(req.method!=='GET'&&req.method!=='HEAD'){res.writeHead(405);res.end();return;}
    let name;
    try {
      name=decodeURIComponent(req.url.split('?')[0]);
      if(!name.startsWith('/')||name.includes('\\')||name.includes('\0')||name.split('/').some(part=>part==='.'||part==='..')) throw Error('bad path');
    } catch {res.writeHead(404);res.end();return;}
    name=name.slice(1);if(!name||name.endsWith('/')) name+='index.html';
    const bytes=files.get(name);
    if(!bytes){res.writeHead(404);res.end();return;}
    res.setHeader('Content-Type',mime[posix.extname(name)]||'application/octet-stream');
    res.writeHead(200);res.end(req.method==='HEAD'?undefined:bytes);
  });
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  return {origin:`http://127.0.0.1:${server.address().port}`,close:()=>new Promise((resolve,reject)=>{server.close(err=>err?reject(err):resolve());server.closeAllConnections();})};
}
