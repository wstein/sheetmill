// This authored legacy fixture and its expected bytes/hash constants were pinned
// before migration integration, at baseline 9f132df. No navi or shell is run.
const migrationLegacy = `---
title: Migration
license: EUPL-1.2
attribution: Fixture authors
tags: [validation, café, smill, validation]
cheatsheet:
  tool: smill
  navi:
    shell: bash
    cards:
      check-sheet:
        params:
          sheet: {type: path, description: Markdown input}
      second: {}
---
## Commands
### Check a sheet {#check-sheet .navi}
` + "```bash\nsmill check \"<sheet>\"\n```\n" + `
### Résumé status {#second .navi}
` + "```bash\nprintf 'first'\nprintf 'second'\n```\n" + `
### Display only {#plain}
` + "```bash\nnot-an-export\n```\n"

const migrationBytes = "; Generated by SheetMill smill build navi; format 1\n; Source: tools/My é#.md\n; Title: Migration\n; Shell: bash\n; Parameters: trusted raw shell text; type hints are not enforced\n; Attribution: Fixture authors\n; License: EUPL-1.2\n\n; card: check-sheet\n% sheetmill:tools/My%20%C3%A9%23.md#check-sheet!, smill, validation, café\n# Check a sheet\nsmill check \"<sheet>\"\n\n; card: second\n% sheetmill:tools/My%20%C3%A9%23.md#second!, smill, validation, café\n# Résumé status\nprintf 'first'\nprintf 'second'\n"

func migrationSheet(t *testing.T, variant string) Sheet {
	t.Helper()
	s := sheet(t, migrationLegacy)
	s.Path = "tools/My é#.md"
	// Direct IR can retain tab-separated titles; emitted descriptions normalize it.
	s.Document.Sections[0].Cards[1].Title = "Résumé\tstatus"
	cheat := s.Document.Metadata["cheatsheet"].(map[string]any)
	legacy := cheat["navi"].(map[string]any)
	cards := legacy["cards"].(map[string]any)
	switch variant {
	case "new", "shared-legacy-marker":
		cheat["cards"] = cards
		delete(cheat, "navi")
	case "dual":
		cheat["cards"] = cards
	case "mixed":
		cheat["cards"] = map[string]any{"second": cards["second"]}
		delete(cards, "second")
	}
	if variant != "legacy" && variant != "shared-legacy-marker" {
		for si := range s.Document.Sections {
			for ci := range s.Document.Sections[si].Cards {
				c := &s.Document.Sections[si].Cards[ci]
				if contains(c.Classes, "navi") {
					if variant == "dual" {
						c.Classes = append(c.Classes, "command")
					} else {
						c.Classes = []string{"command"}
					}
				}
			}
		}
	}
	return s
}

func TestCommandMigrationPinnedOutputAndCompanions(t *testing.T) {
	var identities []sidecarCard
	for _, variant := range []string{"legacy", "new", "dual", "mixed", "shared-legacy-marker"} {
		t.Run(variant, func(t *testing.T) {
			s := migrationSheet(t, variant)
			before, _ := json.Marshal(s.Document.Metadata)
			p, es := Render([]Sheet{s}, Options{})
			if len(es) > 0 || len(p.Warnings) > 0 {
				t.Fatalf("errors=%v warnings=%v", es, p.Warnings)
			}
			if !bytes.Equal(p.Files["demo.cheat"], []byte(migrationBytes)) {
				t.Fatalf("output drift:\n%s", p.Files["demo.cheat"])
			}
			got := parseCheat(p.Files["demo.cheat"])
			wantHashes := []uint64{0x362d24b0c6381291, 0x1d9f85deaea8b6e6}
			if len(got.cards) != len(wantHashes) || got.dropped != 0 {
				t.Fatalf("entries=%+v", got)
			}
			for i, c := range got.cards {
				if h := itemHash(c.tags + c.desc); h != wantHashes[i] {
					t.Fatalf("identity %d=%016x want %016x", i, h, wantHashes[i])
				}
			}
			var sc sidecar
			if err := json.Unmarshal(p.Files["demo.navi.json"], &sc); err != nil {
				t.Fatal(err)
			}
			authored, _ := json.Marshal(sc.Metadata)
			after, _ := json.Marshal(s.Document.Metadata)
			if !bytes.Equal(before, authored) || !bytes.Equal(before, after) {
				t.Fatal("authored metadata changed")
			}
			if identities == nil {
				identities = sc.Cards
			} else if !reflect.DeepEqual(identities, sc.Cards) {
				t.Fatalf("exported identities drift: %+v", sc.Cards)
			}
		})
	}
}

func TestCommandMigrationNamespaceResolution(t *testing.T) {
	for _, tc := range []struct {
		name           string
		shared, legacy any
		want           string
	}{
		{"omitted equals empty", map[string]any{}, map[string]any{"params": map[string]any{}}, ""},
		{"description conflict", map[string]any{"params": map[string]any{"sheet": map[string]any{"type": "path", "description": "Different"}}}, map[string]any{"params": map[string]any{"sheet": map[string]any{"type": "path"}}}, "NAV006"},
		{"partial maps conflict", map[string]any{"params": map[string]any{}}, map[string]any{"params": map[string]any{"sheet": map[string]any{"type": "path"}}}, "NAV006"},
		{"malformed legacy", map[string]any{}, nil, "NAV006"},
		{"malformed shared", nil, map[string]any{}, "CMD001"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			s := migrationSheet(t, "dual")
			cheat := s.Document.Metadata["cheatsheet"].(map[string]any)
			cheat["cards"] = map[string]any{"second": tc.shared}
			cheat["navi"].(map[string]any)["cards"].(map[string]any)["second"] = tc.legacy
			p, es := Render([]Sheet{s}, Options{})
			if tc.want == "" {
				if len(es) > 0 {
					t.Fatal(es)
				}
				return
			}
			found := false
			for _, e := range es {
				found = found || e.Code == tc.want
			}
			if !found || len(p.Files) > 0 {
				t.Fatalf("errors=%v files=%v", es, p.Files)
			}
		})
	}
}

func TestCommandMigrationProfilesWarningsAndCollision(t *testing.T) {
	for _, shell := range ProfileNames() {
		for _, variant := range []string{"legacy", "new", "dual", "mixed", "shared-legacy-marker"} {
			t.Run(shell+"/"+variant, func(t *testing.T) {
				s := migrationSheet(t, variant)
				cheat := s.Document.Metadata["cheatsheet"].(map[string]any)
				if legacy, ok := cheat["navi"].(map[string]any); ok {
					legacy["shell"] = shell
				}
				for si := range s.Document.Sections {
					for ci := range s.Document.Sections[si].Cards {
						for ni := range s.Document.Sections[si].Cards[ci].Content {
							n := &s.Document.Sections[si].Cards[ci].Content[ni]
							if n.Kind == "FencedCodeBlock" {
								n.Properties["language"] = shell
							}
						}
					}
				}
				p, es := Render([]Sheet{s}, Options{Shell: shell})
				if len(es) > 0 || len(p.Warnings) > 0 || p.SheetCount != 1 {
					t.Fatalf("errors=%v warnings=%v", es, p.Warnings)
				}
				want := strings.Replace(migrationBytes, "; Shell: bash\n", "; Shell: "+shell+"\n", 1)
				if string(p.Files["demo.cheat"]) != want {
					t.Fatalf("profile output drift:\n%s", p.Files["demo.cheat"])
				}
				parsed := parseCheat(p.Files["demo.cheat"])
				hashes := []uint64{0x362d24b0c6381291, 0x1d9f85deaea8b6e6}
				if len(parsed.cards) != len(hashes) || parsed.dropped != 0 {
					t.Fatalf("entries=%+v", parsed)
				}
				for i, c := range parsed.cards {
					if got := itemHash(c.tags + c.desc); got != hashes[i] {
						t.Fatalf("entry%d hash=%016x want=%016x", i, got, hashes[i])
					}
				}
			})
		}
	}

	s := migrationSheet(t, "dual")
	if p, es := Render([]Sheet{s}, Options{Shell: "zsh"}); len(es) == 0 || es[0].Code != "NAV006" || len(p.Files) > 0 {
		t.Fatalf("legacy guard lost: %v %+v", es, p)
	}
	s = migrationSheet(t, "new")
	p, es := Render([]Sheet{s}, Options{Shell: "zsh"})
	if len(es) > 0 || len(p.Files) > 0 || len(p.Warnings) != 3 || p.Warnings[0].Code != "NAV101" {
		t.Fatalf("wrong profile: %v %+v", es, p)
	}
	duplicate := migrationSheet(t, "legacy")
	duplicate.ID = "other"
	if p, es := Render([]Sheet{s, duplicate}, Options{}); len(es) == 0 || es[0].Code != "NAV008" || len(p.Files) > 0 {
		t.Fatalf("collision lost: %v %+v", es, p)
	}
	s = migrationSheet(t, "new")
	s.Document.Sections[0].Cards[0].Content[0].Text = "echo <missing>\n"
	p, es = Render([]Sheet{s}, Options{})
	if len(es) > 0 || len(p.Warnings) != 1 || p.Warnings[0].Code != "NAV104" || strings.Contains(string(p.Files["demo.cheat"]), "<missing>") {
		t.Fatalf("placeholder check lost: %v %+v", es, p)
	}
}

func TestCommandMigrationPlaceholderGuidance(t *testing.T) {
	for _, variant := range []string{"legacy", "new", "dual", "mixed", "shared-legacy-marker"} {
		t.Run(variant, func(t *testing.T) {
			s := migrationSheet(t, variant)
			s.Document.Sections[0].Cards[0].Content[0].Text = "echo <missing>\n"
			p, es := Render([]Sheet{s}, Options{})
			namespace := "cheatsheet.cards.check-sheet.params"
			if variant == "legacy" {
				namespace = "cheatsheet.navi.cards.check-sheet.params"
			}
			if len(es) > 0 || len(p.Warnings) != 1 || p.Warnings[0].Code != "NAV104" || !strings.Contains(p.Warnings[0].Message, namespace) {
				t.Fatalf("errors=%v warnings=%v wantpath=%s", es, p.Warnings, namespace)
			}
		})
	}
}
