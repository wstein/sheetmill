func TestContextEncodingAndHash(t *testing.T) {
	if got := encode("a b/ü%,#!.md"); got != "a%20b/%C3%BC%25%2C%23%21.md" {
		t.Fatal(got)
	}
	if itemHash("") == itemHash("a") || itemHash("abc") != itemHash("abc") {
		t.Fatal("hash must be deterministic and input dependent")
	}
	// The ! terminator keeps IDs a/ab with titles bC/C from concatenating alike.
	s := Sheet{Path: "s.md"}
	one := context(s, model.Card{ID: "a"}) + "bC"
	two := context(s, model.Card{ID: "ab"}) + "C"
	if one == two {
		t.Fatal("contexts must not concatenate to the same text")
	}
}

