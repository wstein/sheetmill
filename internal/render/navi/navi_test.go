// parsed is what navi v2.24.0 (parser.rs read_lines and write_cmd) recovers from a
// .cheat file: markers are read at column 0 only, and an entry whose tags and
// description concatenate to one already seen is dropped.
type parsed struct {
	cards    []parsedCard
	dropped  int
	comments int
}
type parsedCard struct{ tags, desc, command string }

// parseCheat is a pure-Go model of the upstream line grammar; nothing is executed.
func parseCheat(b []byte) parsed {
	var p parsed
	var cur *parsedCard
	var tags string
	seen := map[string]bool{}
	inFence := false
	flush := func() {
		if cur != nil {
			cur.command = strings.TrimRight(cur.command, "\n")
			if key := cur.tags + cur.desc; seen[key] {
				p.dropped++
			} else {
				seen[key] = true
				p.cards = append(p.cards, *cur)
			}
			cur = nil
		}
	}
	for _, line := range strings.Split(string(b), "\n") {
		switch {
		case line == "":
			if cur != nil && cur.command != "" {
				cur.command += "\n"
			}
		case line[0] == '%':
			flush()
			tags = strings.TrimSpace(line[1:])
		case line[0] == '@':
			flush()
		case line[0] == ';':
			p.comments++
		case line[0] == '#':
			flush()
			cur = &parsedCard{tags: tags, desc: strings.TrimSpace(line[1:])}
		case line[0] == '$' && strings.Contains(line, ":") && !inFence:
			flush()
		case strings.HasPrefix(line, "```"):
			inFence = !inFence
		default:
			if cur != nil {
				cur.command += line + "\n"
			}
		}
	}
	flush()
	return p
}

func sheet(t *testing.T, source string) Sheet {
	t.Helper()
	d, ds := markdown.Parse([]byte(source))
	if len(ds) > 0 {
		t.Fatalf("source diagnostics: %v", ds)
	}
	return Sheet{ID: "demo", SourceName: "demo.md", Path: "demo.md", Document: d}
}

func card(language, body string) string {
	return "---\ntitle: Demo\nlicense: EUPL-1.2\ncheatsheet:\n  tool: smill\n  navi:\n    cards:\n      c:\n        params:\n          sheet: {type: path}\n---\n## S\n\n### Card {.navi #c}\n\n```" + language + "\n" + body + "\n```\n"
}

func TestGolden(t *testing.T) {
	source := `---
title: SheetMill CLI
license: EUPL-1.2
attribution: Authored for tests
tags: [sheetmill, validation]
cheatsheet:
  tool: smill
  navi:
    shell: bash
    cards:
      check-sheet:
        params:
          sheet: {type: path, description: Markdown sheet to validate}
---
## Validation

### Check a sheet {#check-sheet .navi}

Prose never reaches navi.

| a | b |
| - | - |

` + "```bash\nsmill check \"<sheet>\"\n```" + `

### Not marked {#plain}

` + "```bash\necho hi\n```" + `

### Two blocks {#two .navi}

` + "```bash\na\n```\n\n```bash\nb\n```\n"
	p, errs := Render([]Sheet{sheet(t, source)}, Options{})
	if len(errs) > 0 {
		t.Fatal(errs)
	}
	want := "; Generated by SheetMill smill build navi; format 1\n; Source: demo.md\n; Title: SheetMill CLI\n; Shell: bash\n; Attribution: Authored for tests\n; License: EUPL-1.2\n\n; card: check-sheet\n% sheetmill:demo.md#check-sheet!, smill, sheetmill, validation\n# Check a sheet\nsmill check \"<sheet>\"\n"
	if got := string(p.Files["demo.cheat"]); got != want {
		t.Fatalf("got %q\nwant %q", got, want)
	}
	if len(p.Warnings) != 1 || p.Warnings[0].Code != "NAV101" || !strings.Contains(p.Warnings[0].Message, "two") {
		t.Fatalf("warnings: %v", p.Warnings)
	}
	got := parseCheat(p.Files["demo.cheat"])
	if len(got.cards) != 1 || got.cards[0] != (parsedCard{"sheetmill:demo.md#check-sheet!, smill, sheetmill, validation", "Check a sheet", `smill check "<sheet>"`}) {
		t.Fatalf("parser recovered %+v", got)
	}
}

func TestCardsSkippedWithWarning(t *testing.T) {
	for _, tc := range []struct {
		name, language, body, code string
	}{
		{"unterminated single quote", "bash", "echo 'a <sheet>", "NAV102"},
		{"unterminated double quote", "bash", `echo "a <sheet>`, "NAV102"},
		{"trailing backslash", "bash", "echo <sheet> \\", "NAV102"},
		{"percent line", "bash", "echo <sheet>\n% tags", "NAV102"},
		{"hash line", "bash", "echo <sheet>\n# comment", "NAV102"},
		{"dollar line", "bash", "echo <sheet>\n$ v: cmd", "NAV102"},
		{"at line", "bash", "echo <sheet>\n@ other", "NAV102"},
		{"semicolon line", "bash", "echo <sheet>\n; x", "NAV102"},
		{"heredoc marker line", "bash", "cat <<EOF <sheet>\n%payload\nEOF", "NAV102"},
		{"blank line", "bash", "echo <sheet>\n\necho b", "NAV102"},
		{"carriage return", "bash", "echo <sheet>\r\necho", "NAV102"},
		{"bidi control", "bash", "echo <sheet> \u202e", "NAV102"},
		{"NUL", "bash", "echo <sheet>\x00", "NAV102"},
		{"unsupported language", "python", "print('<sheet>')", "NAV101"},
		{"other shell", "fish", "echo <sheet>", "NAV101"},
		{"uppercase placeholder", "bash", "echo <sheet> <Name>", "NAV103"},
		{"hyphen placeholder", "bash", "echo <sheet> <a-b>", "NAV103"},
		{"undeclared placeholder", "bash", "echo <sheet> <other>", "NAV104"},
		{"unused declaration", "bash", "echo hi", "NAV104"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			p, errs := Render([]Sheet{sheet(t, card(tc.language, tc.body))}, Options{})
			if len(errs) > 0 {
				t.Fatalf("a card problem must be a warning, got errors %v", errs)
			}
			if len(p.Warnings) != 2 || p.Warnings[0].Code != tc.code || p.Warnings[1].Code != "NAV106" {
				t.Fatalf("warnings %v, want %s then NAV106", p.Warnings, tc.code)
			}
			if got := parseCheat(p.Files["demo.cheat"]); len(got.cards) != 0 {
				t.Fatalf("skipped card was exported: %+v", got)
			}
		})
	}
}

