// FuzzCommand asserts a command is either refused or recovered unchanged by the
// grammar model, with no extra structure appearing.
func FuzzCommand(f *testing.F) {
	for _, s := range []string{"echo <sheet>", "echo 'a", "x\n% t", "cat <<E\n#\nE", "a \\", "$'a\\'b' <sheet>", "echo <sheet>\n  % ok"} {
		f.Add(s)
	}
	f.Fuzz(func(t *testing.T, command string) {
		if strings.Contains(command, "```") || strings.Contains(command, "~~~") {
			return // would end the source fence, not the command text under test
		}
		source := "---\ntitle: T\nlicense: x\ncheatsheet:\n  navi:\n    cards:\n      c: {params: {sheet: {type: path}}}\n---\n## S\n\n### C {.navi #c}\n\n```bash\n" + command + "\n```\n"
		d, ds := markdown.Parse([]byte(source))
		if len(ds) > 0 {
			return
		}
		p, errs := Render([]Sheet{{ID: "f", SourceName: "f.md", Document: d}}, Options{})
		if len(errs) > 0 {
			return
		}
		got := parseCheat(p.Files["f.cheat"])
		if len(structuralWarnings(p)) > 2 {
			t.Fatalf("unexpected warnings %v", p.Warnings)
		}
		if _, exported := p.Files["f.cheat"]; !exported {
			return // card skipped with a warning
		}
		want := strings.TrimRight(command, "\n")
		if len(got.cards) != 1 || got.cards[0].command != want || got.cards[0].desc != "C" || got.dropped != 0 || !strings.HasPrefix(got.cards[0].tags, "sheetmill:") {
			t.Fatalf("command %q recovered as %+v", command, got)
		}
	})
}

// TestNoExecution is the S6 lint: the package must not be able to run anything.
func TestNoExecution(t *testing.T) {
	files, _ := filepath.Glob("*.go")
	for _, name := range files {
		f, err := parser.ParseFile(token.NewFileSet(), name, nil, parser.ImportsOnly)
		if err != nil {
			t.Fatal(err)
		}
		for _, imp := range f.Imports {
			switch strings.Trim(imp.Path.Value, `"`) {
			case "os/exec", "syscall", "plugin", "net", "net/http":
				t.Errorf("%s imports %s; the navi renderer must stay execution- and network-free", name, imp.Path.Value)
			}
		}
	}
	_ = os.Stdout
}

